"""Create the two delivery ZIPs in release/:
  SP-Residence-Website-Source.zip           complete project (no node_modules / dist)
  SP-Residence-Website-Ready-To-Upload.zip  the built website (run `npm run build` first)
Usage: python3 tools/make_zip.py
"""
import os
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "release")
SKIP_DIRS = {"node_modules", "dist", "release", ".git", "test-results", "__pycache__"}
SKIP_FILES = {".DS_Store"}


def add_tree(z, base, prefix):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if f in SKIP_FILES or f.endswith(".bak"):
                continue
            if os.path.basename(dirpath) == "screenshots" and os.path.basename(os.path.dirname(dirpath)) == "tests" and f.endswith(".png"):
                continue  # regenerated by the test run
            full = os.path.join(dirpath, f)
            rel = os.path.relpath(full, base)
            z.write(full, os.path.join(prefix, rel))


def main():
    os.makedirs(OUT, exist_ok=True)
    src = os.path.join(OUT, "SP-Residence-Website-Source.zip")
    with zipfile.ZipFile(src, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        add_tree(z, ROOT, "sp-residency-3d")
    print("wrote", src, round(os.path.getsize(src) / 1e6, 1), "MB")
    dist = os.path.join(ROOT, "dist")
    if os.path.isdir(dist):
        web = os.path.join(OUT, "SP-Residence-Website-Ready-To-Upload.zip")
        with zipfile.ZipFile(web, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
            add_tree(z, dist, "dist")
        print("wrote", web, round(os.path.getsize(web) / 1e6, 1), "MB")
    else:
        print("dist/ not found - run `npm run build` first for the ready-to-upload ZIP")


if __name__ == "__main__":
    main()
